function generate_MG_mat()
% =========================================================
% generate_MG_mat.m
%
% 生成 Mackey-Glass 时间序列
%
% 内部数值积分：
%   RK4
%   dt = 0.1
%
% 最终数据采样：
%   每 10 个积分点取 1 个
%   因此最终 MG 数据采样间隔为：
%       10 × 0.1 = 1
%
% 最终输出：
%   8000 个 MG 数据点
%
% 保存位置：
%   MG1/MG.mat
%
% 保存变量：
%   MG
%
% 模型：
%
%   dx/dt =
%       beta * x(t-tau) / (1 + x(t-tau)^n)
%       - gamma * x(t)
%
% =========================================================

clc;
close all;

%% =========================================================
% 1. Mackey-Glass 参数
% =========================================================

beta  = 0.2;
gamma = 0.1;
n     = 10;

tau = 17;                 % 延迟时间
dt  = 0.1;                % RK4 内部积分步长

%% =========================================================
% 2. 最终数据设置
% =========================================================

N = 8000;                 % 最终需要的 MG 数据点数

sample_stride = 20;       % 每10个积分点取1个

sample_interval = ...
    sample_stride * dt;   % 最终数据采样间隔

% 为了最终得到8000个点，
% 内部需要积分80000个小步
N_internal = N * sample_stride;

fprintf('========================================\n');
fprintf('Mackey-Glass 数据生成参数\n');
fprintf('========================================\n');
fprintf('内部积分步长 dt       = %.3f\n', dt);
fprintf('降采样间隔            = %d 个积分点\n', sample_stride);
fprintf('最终数据采样间隔      = %.3f\n', sample_interval);
fprintf('最终数据点数          = %d\n', N);
fprintf('内部积分步数          = %d\n', N_internal);
fprintf('========================================\n\n');

%% =========================================================
% 3. 延迟对应的积分步数
% =========================================================

delay_steps = round(tau / dt);

if abs(delay_steps - tau / dt) > 1e-12
    error(['tau/dt 必须为整数。' ...
           '当前 tau = %.4g, dt = %.4g。'], ...
           tau, dt);
end

fprintf('tau = %.3f\n', tau);
fprintf('delay_steps = %d\n\n', delay_steps);

%% =========================================================
% 4. 历史初值 t ∈ [-tau, 0]
% =========================================================

% 为了保证每次生成结果可重复
rng(1);

% 常数历史 + 微小随机扰动
x_hist = 1.2 * ones(delay_steps + 1, 1);

x_hist = x_hist + ...
    1e-3 * randn(size(x_hist));

%% =========================================================
% 5. 分配完整积分序列
% =========================================================
%
% 前 delay_steps + 1 个点：
%   t ∈ [-tau, 0]
%
% 后面生成 N_internal 个新点
%

x = zeros( ...
    delay_steps + 1 + N_internal, ...
    1);

x(1 : delay_steps + 1) = x_hist;

%% =========================================================
% 6. Mackey-Glass 右端函数
% =========================================================

mg_rhs = @(x_now, x_delay) ...
    (beta * x_delay / ...
    (1 + x_delay^n) ...
    - gamma * x_now);

%% =========================================================
% 7. RK4 积分
% =========================================================

fprintf('开始生成 Mackey-Glass 序列...\n');

for step = 1:N_internal

    % 当前状态在完整数组中的位置
    i = delay_steps + step;

    x_now = x(i);

    % 对应 t - tau 的状态
    x_delay = x(i - delay_steps);

    % -----------------------------------------------------
    % K1
    % -----------------------------------------------------

    k1 = mg_rhs( ...
        x_now, ...
        x_delay);

    % -----------------------------------------------------
    % K2
    % -----------------------------------------------------

    k2 = mg_rhs( ...
        x_now + 0.5 * dt * k1, ...
        x_delay);

    % -----------------------------------------------------
    % K3
    % -----------------------------------------------------

    k3 = mg_rhs( ...
        x_now + 0.5 * dt * k2, ...
        x_delay);

    % -----------------------------------------------------
    % K4
    % -----------------------------------------------------

    k4 = mg_rhs( ...
        x_now + dt * k3, ...
        x_delay);

    % -----------------------------------------------------
    % 更新
    % -----------------------------------------------------

    x(i + 1) = ...
        x_now + ...
        (dt / 6) * ...
        (k1 + 2*k2 + 2*k3 + k4);

end

fprintf('内部积分完成。\n\n');

%% =========================================================
% 8. 提取内部积分得到的 MG 序列
% =========================================================
%
% internal_MG 的采样间隔仍然是：
%
%   dt = 0.1
%

internal_MG = ...
    x(delay_steps + 2 : ...
      delay_steps + 1 + N_internal);

%% =========================================================
% 9. 每10个积分点取1个
% =========================================================
%
% internal_MG:
%
%   t = 0.1, 0.2, 0.3, ..., 8000
%
% 我们取：
%
%   t = 1, 2, 3, ..., 8000
%
% 即：
%
%   internal_MG(10)
%   internal_MG(20)
%   internal_MG(30)
%   ...
%

MG = internal_MG( ...
    sample_stride : ...
    sample_stride : ...
    N_internal);

% 强制转换成列向量
MG = MG(:);

%% =========================================================
% 10. 检查最终长度
% =========================================================

if length(MG) ~= N

    error( ...
        'MG长度错误：期望 %d，实际 %d。', ...
        N, ...
        length(MG));

end

%% =========================================================
% 11. 可视化最终MG序列
% =========================================================

figure( ...
    'Color', 'w', ...
    'Name', 'Mackey-Glass Sequence');

plot( ...
    MG, ...
    'k', ...
    'LineWidth', 1);

grid on;

xlabel('n');

ylabel('MG(n)');

title(sprintf( ...
    ['Mackey-Glass: ' ...
     'beta=%.2f, gamma=%.2f, ' ...
     'n=%d, tau=%g, ' ...
     'dt_{int}=%.1f, ' ...
     '\\Delta t_{sample}=%.1f'], ...
    beta, ...
    gamma, ...
    n, ...
    tau, ...
    dt, ...
    sample_interval));

%% =========================================================
% 12. 创建保存文件夹 MG1
% =========================================================

save_folder = 'MG1';

if ~exist(save_folder, 'dir')

    mkdir(save_folder);

end

%% =========================================================
% 13. 保存
% =========================================================

save_file = fullfile( ...
    save_folder, ...
    'MG.mat');

save(save_file, 'MG');

%% =========================================================
% 14. 输出信息
% =========================================================

fprintf('========================================\n');
fprintf('MG 数据生成完成\n');
fprintf('========================================\n');

fprintf('RK4积分步长：\n');
fprintf('  dt = %.3f\n\n', dt);

fprintf('降采样：\n');
fprintf('  每 %d 个积分点取1个\n', ...
    sample_stride);

fprintf('最终采样间隔：\n');
fprintf('  Delta_t = %.3f\n\n', ...
    sample_interval);

fprintf('内部积分数据点数：\n');
fprintf('  %d\n\n', ...
    N_internal);

fprintf('最终MG数据点数：\n');
fprintf('  %d\n\n', ...
    length(MG));

fprintf('数据尺寸：\n');
fprintf('  %d × %d\n\n', ...
    size(MG, 1), ...
    size(MG, 2));

fprintf('保存文件：\n');
fprintf('  %s\n', save_file);

fprintf('========================================\n');

end